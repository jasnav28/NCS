function normalizeSlug(str) {
  if (!str) return '';
  return decodeURIComponent(str)
    .toUpperCase()
    .replace(/[,_/+\s]+/g, '-')
    .replace(/-+/g, '-')
    .trim();
}

export function findProductBySlug(slug) {
  return getProductForSlug(slug) || PRODUCTS[0];
}

export function findProductByBrand(brand) {
  return getProductForSlug(brand) || PRODUCTS[0];
}

export function getProductForSlug(slug) {
  if (!slug) return null;
  const target = normalizeSlug(slug);

  for (const product of PRODUCTS) {
    if (normalizeSlug(product.slug) === target) return product;
    if (normalizeSlug(product.brand) === target) return product;
    
    // Check individual names if product brand has multiple slash or comma-separated names
    const names = product.brand.split(/[,/]/).map(n => normalizeSlug(n));
    if (names.includes(target)) return product;
  }

  return null;
}
